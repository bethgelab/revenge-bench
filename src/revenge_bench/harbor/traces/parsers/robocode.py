def _parse_robot_elem(robot_elem: ET.Element) -> dict:
    """Parse a <robot> XML element into a dict of attributes."""
    return {
        "id": robot_elem.get("id", ""),
        "name": robot_elem.get("name", ""),
        "vsName": robot_elem.get("vsName", ""),
        "teamName": robot_elem.get("teamName", ""),
        "state": robot_elem.get("state", "ACTIVE"),
        "x": float(robot_elem.get("x", 0)),
        "y": float(robot_elem.get("y", 0)),
        "bodyHeading": float(robot_elem.get("bodyHeading", 0)),
        "gunHeading": float(robot_elem.get("gunHeading", 0)),
        "radarHeading": float(robot_elem.get("radarHeading", 0)),
        "energy": float(robot_elem.get("energy", 0)),
        "velocity": float(robot_elem.get("velocity", 0)),
        "gunHeat": float(robot_elem.get("gunHeat", 0)),
    }


def _parse_bullet_elem(bullet_elem: ET.Element) -> dict:
    """Parse a <bullet> XML element into a dict."""
    return {
        "id": bullet_elem.get("id", ""),
        "owner": bullet_elem.get("owner", ""),
        "state": bullet_elem.get("state", ""),
        "x": float(bullet_elem.get("x", 0)),
        "y": float(bullet_elem.get("y", 0)),
        "heading": float(bullet_elem.get("heading", 0)),
        "power": float(bullet_elem.get("power", 0)),
    }


def _parse_turn_elem(turn_elem: ET.Element) -> dict:
    """Parse a <turn> XML element into a structured dict."""
    robots = []
    robots_elem = turn_elem.find("robots")
    if robots_elem is not None:
        for robot_elem in robots_elem.findall("robot"):
            robots.append(_parse_robot_elem(robot_elem))

    bullets = []
    bullets_elem = turn_elem.find("bullets")
    if bullets_elem is not None:
        for bullet_elem in bullets_elem.findall("bullet"):
            bullets.append(_parse_bullet_elem(bullet_elem))

    return {
        "round": int(turn_elem.get("round", 0)),
        "turn": int(turn_elem.get("turn", 0)),
        "robots": robots,
        "bullets": bullets,
    }


def _rad_to_deg(radians: float) -> float:
    """Convert radians to degrees."""
    return math.degrees(radians)


def _normalize_angle_delta(delta_rad: float) -> float:
    """Normalize an angle delta in radians to [-pi, pi], then convert to degrees."""
    # Normalize to [-pi, pi]
    while delta_rad > math.pi:
        delta_rad -= 2 * math.pi
    while delta_rad < -math.pi:
        delta_rad += 2 * math.pi
    return math.degrees(delta_rad)


def _find_robot_by_name(robots: list[dict], player_name: str) -> dict | None:
    """Find a robot by player name (matching against name or teamName)."""
    for robot in robots:
        # Match against teamName (e.g., "player1.MyTank*") or name
        name = robot.get("teamName", "") or robot.get("name", "")
        # Strip the class name suffix for matching: "player1.MyTank*" -> "player1"
        base_name = name.split(".")[0] if "." in name else name
        if base_name == player_name or name == player_name:
            return robot
    # Fallback: try vsName
    for robot in robots:
        vs_name = robot.get("vsName", "")
        base_name = vs_name.split(".")[0] if "." in vs_name else vs_name
        if base_name == player_name or vs_name == player_name:
            return robot
    return None


def _find_robot_by_id(robots: list[dict], robot_id: str) -> dict | None:
    """Find a robot by its id."""
    for robot in robots:
        if robot.get("id") == robot_id:
            return robot
    return None


def _resolve_bullet_owner(bullet: dict) -> str | None:
    """Resolve bullet owner id from explicit owner field or id prefix.

    RoboCode XML can omit the ``owner`` attribute and encode ownership in the
    bullet id (e.g. ``0-12`` or ``1-10002``). In that case we extract the
    numeric prefix before the first ``-``.
    """
    owner = bullet.get("owner")
    if owner not in (None, ""):
        return str(owner)

    bullet_id = str(bullet.get("id", ""))
    if not bullet_id:
        return None

    prefix, sep, _ = bullet_id.partition("-")
    if not sep:
        return None
    if prefix.isdigit():
        return prefix
    return None


