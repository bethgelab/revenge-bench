"""
RoboCode Trace Parser

Converts RoboCode's native XML recording format to our unified GameTrace format.

Also provides game-specific utility functions:
- normalize_action(): Ensure action dict has all components
- actions_distance(): Compute normalized distance between actions (0=identical, 1=different)

================================================================================
CANONICAL ACTION FORMAT:
================================================================================
Actions are dicts with 5 float components, inferred from consecutive turns:

    {
        "velocity": float,      # [-8, 8] px/turn
        "turn_body": float,     # [-10, 10] degrees/turn
        "turn_gun": float,      # [-20, 20] degrees/turn
        "turn_radar": float,    # [-45, 45] degrees/turn
        "fire_power": float,    # [0, 3] (0 = no fire)
    }

Normalization ranges (from RoboCode game rules):
    velocity:   max 8 px/turn
    turn_body:  max 10 deg/turn
    turn_gun:   max 20 deg/turn
    turn_radar: max 45 deg/turn
    fire_power: range 0-3

================================================================================
RAW FIELDS (from XML recording):
================================================================================
File format: XML (record_*.xml, 12-30MB per game)
Generated by: robocode.sh -recordXML <path>

Root element: <record>
  <turn round="0" turn="5" ver="1">
    <robots>
      <robot id="0" vsName="MyTank*" state="ACTIVE"
             energy="100.0" x="730.158" y="101.480"
             bodyHeading="2.047" gunHeading="1.305" radarHeading="5.232"
             gunHeat="2.5" velocity="5.0"
             teamName="player1.MyTank*" name="player1.MyTank*">
        <score totalScore="0.0" currentScore="0.0" .../>
      </robot>
    </robots>
        <bullets>
            <bullet id="0" owner="0" state="FIRED"
              x="100.0" y="200.0" heading="1.5" power="2.0"/>
            <bullet id="0-12" state="FIRED"
              x="110.0" y="210.0" heading="1.6" power="1.5"/>
        </bullets>
  </turn>

Note: Headings in XML are in RADIANS. We convert to degrees in state dicts.

================================================================================
INFERRED FIELDS (computed by parser):
================================================================================
    - velocity:   from position delta between turns
    - turn_body:  from bodyHeading delta (radians -> degrees)
    - turn_gun:   from gunHeading delta (radians -> degrees)
    - turn_radar: from radarHeading delta (radians -> degrees)
    - fire_power: from new bullets appearing (matched by explicit owner or id prefix)

    - player_states: Simplified numeric dict per player
    - metadata.timestamp: Current time (RoboCode doesn't include timestamp)
    - results[].outcome: GameOutcome computed from final scores
================================================================================
"""

