class RoboCodeTraceParser:
    """
    Parser for RoboCode's native XML recording format.

    Usage:
        parser = RoboCodeTraceParser()
        trace = parser.parse_file("record_0.xml")
    """

    GAME_TYPE = "RoboCode"

    def __init__(self, arena_width: int = 800, arena_height: int = 600):
        """
        Initialize the parser.

        Args:
            arena_width: Battlefield width (default 800)
            arena_height: Battlefield height (default 600)
        """
        self.arena_width = arena_width
        self.arena_height = arena_height

    def parse_file(self, path: str | Path, source: dict | None = None) -> GameTrace:
        """
        Parse a RoboCode XML recording file.

        Args:
            path: Path to the XML file
            source: Optional source metadata (tournament_id, etc.)

        Returns:
            GameTrace object
        """
        path = Path(path)
        try:
            tree = ET.parse(str(path))
        except ET.ParseError:
            # RoboCode engine appends trailing garbage bytes after valid XML.
            # Strip them and retry.
            raw = path.read_bytes()
            if raw[:2] == b"\x1f\x8b":
                raw = gzip.decompress(raw)
            text = raw.decode("utf-8", errors="replace")
            text = re.sub(r"[^\x09\x0A\x0D\x20-\uD7FF\uE000-\uFFFD]", "", text)
            tree = ET.ElementTree(ET.fromstring(text))
        root = tree.getroot()
        return self._parse_root(root, source)

    def _parse_root(self, root: ET.Element, source: dict | None = None) -> GameTrace:
        """Internal parsing logic."""

        # Parse all turns
        turn_elems = root.findall(".//turn")
        if not turn_elems:
            raise ValueError("No <turn> elements found in XML")

        parsed_turns = [_parse_turn_elem(elem) for elem in turn_elems]

        # Extract player list from first turn
        first_turn = parsed_turns[0]
        players = []
        for robot in first_turn.get("robots", []):
            name = robot.get("teamName", "") or robot.get("name", "")
            base_name = name.split(".")[0] if "." in name else name
            players.append(
                {
                    "id": robot.get("id", ""),
                    "name": base_name,
                }
            )

        # Determine game_id
        game_id = source.get("game_id", "robocode-game") if source else "robocode-game"

        # Count rounds
        rounds_seen = set()
        for t in parsed_turns:
            rounds_seen.add(t.get("round", 0))

        metadata = GameMetadata(
            game_id=game_id,
            game_type=self.GAME_TYPE,
            timestamp=datetime.now(),
            players=players,
            config={
                "width": self.arena_width,
                "height": self.arena_height,
                "num_rounds": len(rounds_seen),
            },
            source=source or {},
        )

        # Build TurnRecords
        turns = []
        prev_turn_data = None

        for turn_data in parsed_turns:
            turn_num = turn_data.get("turn", 0)

            # Build state (common)
            state = {
                "round": turn_data.get("round", 0),
                "turn": turn_num,
                "robots": turn_data.get("robots", []),
                "bullets": turn_data.get("bullets", []),
            }

            # Build player-specific states
            player_states = {}
            for robot in turn_data.get("robots", []):
                name = robot.get("teamName", "") or robot.get("name", "")
                base_name = name.split(".")[0] if "." in name else name
                player_state = extract_player_state(
                    turn_data, base_name, self.arena_width, self.arena_height
                )
                if player_state is not None:
                    player_states[base_name] = player_state

            # Infer actions from previous turn
            actions = []
            if prev_turn_data is not None and prev_turn_data.get(
                "round"
            ) == turn_data.get("round"):
                for robot in turn_data.get("robots", []):
                    name = robot.get("teamName", "") or robot.get("name", "")
                    base_name = name.split(".")[0] if "." in name else name
                    action = extract_player_action(prev_turn_data, turn_data, base_name)
                    if action is not None:
                        actions.append(
                            PlayerAction(
                                player_id=robot.get("id", ""),
                                player_name=base_name,
                                turn=prev_turn_data.get("turn", 0),
                                action=action,
                                action_type="robot_control",
                            )
                        )

            prev_turn_data = turn_data

            turns.append(
                TurnRecord(
                    turn=turn_num,
                    state=state,
                    actions=actions,
                    player_states=player_states,
                )
            )

        # Determine winner from final scores
        winner_name = None
        is_draw = False
        final_scores = {}

        # Get scores from the last turn of the last round
        if parsed_turns:
            last_turn = parsed_turns[-1]
            for robot in last_turn.get("robots", []):
                name = robot.get("teamName", "") or robot.get("name", "")
                base_name = name.split(".")[0] if "." in name else name
                final_scores[base_name] = robot.get("energy", 0.0)

        if final_scores:
            max_score = max(final_scores.values())
            winners = [
                name for name, score in final_scores.items() if score == max_score
            ]
            if len(winners) == 1:
                winner_name = winners[0]
            else:
                is_draw = True

        # Build results
        results = []
        for player in players:
            player_name = player["name"]
            if player_name == winner_name:
                outcome = GameOutcome.WIN
            elif is_draw:
                outcome = GameOutcome.DRAW
            else:
                outcome = GameOutcome.LOSS

            results.append(
                PlayerResult(
                    player_id=player["id"],
                    player_name=player_name,
                    outcome=outcome,
                )
            )

        return GameTrace(
            metadata=metadata,
            turns=turns,
            results=results,
            winner=winner_name,
            is_draw=is_draw,
        )


def parse_robocode_trace(path: str | Path, **kwargs) -> GameTrace:
    """Convenience function to parse a RoboCode trace file."""
    return RoboCodeTraceParser(**kwargs).parse_file(path)
