# =============================================================================
# Constants
# =============================================================================

ACTION_COMPONENTS = ["velocity", "turn_body", "turn_gun", "turn_radar", "fire_power"]

# Normalization ranges from RoboCode game rules
ACTION_RANGES = {
    "velocity": 8.0,  # [-8, 8]
    "turn_body": 10.0,  # [-10, 10] degrees
    "turn_gun": 20.0,  # [-20, 20] degrees
    "turn_radar": 45.0,  # [-45, 45] degrees
    "fire_power": 3.0,  # [0, 3]
}


# =============================================================================
# Action Normalization & Comparison
# =============================================================================


def normalize_action(action: Any) -> dict | None:
    """
    Normalize RoboCode action to canonical dict format.

    Canonical format: dict with keys velocity, turn_body, turn_gun, turn_radar, fire_power.
    Missing keys default to 0.0.

    Input formats:
        - dict with any subset of action keys -> filled with 0.0 defaults
        - None -> None

    Returns:
        Dict with all 5 action components as floats, or None if invalid.
    """
    if action is None:
        return None

    if not isinstance(action, dict):
        return None

    return {key: float(action.get(key, 0.0)) for key in ACTION_COMPONENTS}


def actions_distance(a1: Any, a2: Any) -> float:
    """
    Compute normalized distance between two RoboCode actions.

    Each component's absolute difference is normalized to [0, 1] by its valid range,
    then averaged across all 5 components.

    Returns:
        Float in [0, 1] where 0.0 = identical, 1.0 = maximally different.
        Returns 1.0 if either action is None/invalid.
    """
    n1 = normalize_action(a1)
    n2 = normalize_action(a2)

    if n1 is None or n2 is None:
        return 1.0

    total_diff = 0.0
    for key in ACTION_COMPONENTS:
        range_val = ACTION_RANGES[key]
        # For symmetric ranges like velocity [-8, 8], max diff = 16, so divide by 2*range
        # For fire_power [0, 3], max diff = 3, so divide by range
        if key == "fire_power":
            max_diff = range_val
        else:
            max_diff = 2.0 * range_val
        diff = abs(n1[key] - n2[key]) / max_diff
        total_diff += min(diff, 1.0)  # Clamp to [0, 1]

    return total_diff / len(ACTION_COMPONENTS)


