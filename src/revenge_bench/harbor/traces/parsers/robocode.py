def extract_player_state(
    turn_data: dict, player_name: str, arena_width: int = 800, arena_height: int = 600
) -> dict | None:
    """
    Extract a player's view of the game state as a simplified numeric dict.

    Args:
        turn_data: Parsed turn dict (from _parse_turn_elem)
        player_name: Name of the player whose perspective to extract
        arena_width: Battlefield width
        arena_height: Battlefield height

    Returns:
        Simplified numeric state dict, or None if player not found.
    """
    robots = turn_data.get("robots", [])
    my_robot = _find_robot_by_name(robots, player_name)
    if my_robot is None:
        return None

    # Find enemy (closest if multiple)
    enemies = [
        r
        for r in robots
        if r.get("id") != my_robot.get("id") and r.get("state") != "DEAD"
    ]

    state = {
        "tick": turn_data.get("turn", 0),
        "my_x": my_robot["x"],
        "my_y": my_robot["y"],
        "my_heading": _rad_to_deg(my_robot["bodyHeading"]),
        "my_gun_heading": _rad_to_deg(my_robot["gunHeading"]),
        "my_radar_heading": _rad_to_deg(my_robot["radarHeading"]),
        "my_energy": my_robot["energy"],
        "my_velocity": my_robot["velocity"],
        "my_gun_heat": my_robot["gunHeat"],
        "arena_width": arena_width,
        "arena_height": arena_height,
    }

    if enemies:
        # Pick closest enemy
        closest = min(
            enemies,
            key=lambda e: math.sqrt(
                (e["x"] - my_robot["x"]) ** 2 + (e["y"] - my_robot["y"]) ** 2
            ),
        )
        dist = math.sqrt(
            (closest["x"] - my_robot["x"]) ** 2 + (closest["y"] - my_robot["y"]) ** 2
        )
        # Bearing: angle from my heading to enemy, in degrees
        # RoboCode uses heading-from-North, clockwise → atan2(dx, dy)
        angle_to_enemy = math.atan2(
            closest["x"] - my_robot["x"], closest["y"] - my_robot["y"]
        )
        bearing = _normalize_angle_delta(angle_to_enemy - my_robot["bodyHeading"])

        state.update(
            {
                "enemy_x": closest["x"],
                "enemy_y": closest["y"],
                "enemy_heading": _rad_to_deg(closest["bodyHeading"]),
                "enemy_energy": closest["energy"],
                "enemy_velocity": closest["velocity"],
                "enemy_distance": dist,
                "enemy_bearing": bearing,
            }
        )

        if len(enemies) > 1:
            state["enemy_count"] = len(enemies)
    else:
        # No enemies visible - fill with defaults
        state.update(
            {
                "enemy_x": 0.0,
                "enemy_y": 0.0,
                "enemy_heading": 0.0,
                "enemy_energy": 0.0,
                "enemy_velocity": 0.0,
                "enemy_distance": 0.0,
                "enemy_bearing": 0.0,
            }
        )

    return state


def extract_player_action(
    turn_data: dict,
    next_turn_data: dict,
    player_name: str,
) -> dict | None:
    """
    Infer a player's action by comparing state between consecutive turns.

    Actions inferred:
    - velocity: from position delta (approximate)
    - turn_body: from bodyHeading delta
    - turn_gun: from gunHeading delta
    - turn_radar: from radarHeading delta
        - fire_power: from new bullets appearing with this robot as owner.
            Ownership is resolved from bullet.owner when present, otherwise from
            the bullet id prefix before the first "-" (e.g. "0-12" -> owner "0").

    Args:
        turn_data: Current turn data
        next_turn_data: Next turn data
        player_name: Name of the player

    Returns:
        Action dict or None if player not found in either turn.
    """
    robots_curr = turn_data.get("robots", [])
    robots_next = next_turn_data.get("robots", [])

    my_robot_curr = _find_robot_by_name(robots_curr, player_name)
    my_robot_next = _find_robot_by_name(robots_next, player_name)

    if my_robot_curr is None or my_robot_next is None:
        return None

    # Velocity is directly available in the next turn's state
    velocity = my_robot_next["velocity"]

    # Turn rates from heading deltas (in radians, convert to degrees).
    # These are total heading deltas from the physics engine, which is what
    # the learner's move(state) function should return.
    turn_body = _normalize_angle_delta(
        my_robot_next["bodyHeading"] - my_robot_curr["bodyHeading"]
    )
    turn_gun = _normalize_angle_delta(
        my_robot_next["gunHeading"] - my_robot_curr["gunHeading"]
    )
    turn_radar = _normalize_angle_delta(
        my_robot_next["radarHeading"] - my_robot_curr["radarHeading"]
    )

    # Fire power: check for new bullets owned by this robot
    robot_id = my_robot_curr["id"]
    curr_bullet_ids = {
        str(b.get("id", ""))
        for b in turn_data.get("bullets", [])
        if _resolve_bullet_owner(b) == robot_id and b.get("id")
    }
    next_bullets = next_turn_data.get("bullets", [])
    new_bullets = [
        b
        for b in next_bullets
        if _resolve_bullet_owner(b) == robot_id
        and str(b.get("id", "")) not in curr_bullet_ids
    ]

    fire_power = 0.0
    if new_bullets:
        # Use the power of the first new bullet
        fire_power = new_bullets[0].get("power", 0.0)

    return {
        "velocity": velocity,
        "turn_body": turn_body,
        "turn_gun": turn_gun,
        "turn_radar": turn_radar,
        "fire_power": fire_power,
    }


def extract_state_action_pairs(
    xml_file: Path | str,
    player_name: str,
    arena_width: int = 800,
    arena_height: int = 600,
) -> list[tuple[dict, dict]]:
    """
    Extract all (state, action) pairs for a player from an XML recording file.

    This is the main function for offline evaluation - it reads an XML file and
    returns all the states the player saw and actions they took.

    Args:
        xml_file: Path to record_*.xml file
        player_name: Name of the player to extract data for
        arena_width: Battlefield width (default 800)
        arena_height: Battlefield height (default 600)

    Returns:
        List of (state, action) tuples where:
        - state: Simplified numeric dict the player saw
        - action: Action dict the player took (inferred from state changes)
    """
    xml_file = Path(xml_file)

    # Parse XML - use iterparse for efficiency with large files.
    # RoboCode's engine can produce XML with invalid characters (control chars,
    # null bytes) so we sanitize the raw bytes before parsing.  The file may
    # also be truncated (engine killed mid-write); iterparse still yields the
    # turns parsed before the error, so we collect what we can.
    turns = []
    try:
        for _event, elem in ET.iterparse(str(xml_file), events=["end"]):
            if elem.tag == "turn":
                turns.append(_parse_turn_elem(elem))
                elem.clear()
    except ET.ParseError:
        if turns:
            pass  # keep turns parsed before the error
        else:
            # No turns recovered – sanitize and retry
            raw = xml_file.read_bytes()
            # Detect gzip (magic bytes 1f 8b)
            if raw[:2] == b"\x1f\x8b":
                raw = gzip.decompress(raw)
            text = raw.decode("utf-8", errors="replace")
            # Remove characters invalid in XML 1.0
            text = re.sub(r"[^\x09\x0A\x0D\x20-\uD7FF\uE000-\uFFFD]", "", text)
            try:
                for _event, elem in ET.iterparse(
                    io.BytesIO(text.encode("utf-8")), events=["end"]
                ):
                    if elem.tag == "turn":
                        turns.append(_parse_turn_elem(elem))
                        elem.clear()
            except ET.ParseError:
                pass  # keep whatever turns were parsed before truncation

    # Extract state-action pairs from consecutive turns
    pairs = []
    for i in range(len(turns) - 1):
        turn_data = turns[i]
        next_turn_data = turns[i + 1]

        # Only process turns within the same round
        if turn_data.get("round") != next_turn_data.get("round"):
            continue

        state = extract_player_state(turn_data, player_name, arena_width, arena_height)
        if state is None:
            continue

        action = extract_player_action(turn_data, next_turn_data, player_name)
        if action is None:
            continue

        pairs.append((state, action))

    return pairs


def build_probe_trace_payload(
    simulations: list[tuple[str, Path]],
    probe_id: int,
    *,
    probe_player: str = "p0",
    target_player: str = "p1",
) -> dict[str, Any]:
    """Build normal-path RoboCode probe output from XML recording files."""
    all_pairs: list[dict[str, Any]] = []
    per_simulation: list[dict[str, Any]] = []

    for filename, xml_file in simulations:
        target_pairs = extract_state_action_pairs(xml_file, target_player)
        probe_pairs = extract_state_action_pairs(xml_file, probe_player)

        target_by_tick = {
            state.get("tick", i): (state, action)
            for i, (state, action) in enumerate(target_pairs)
        }
        probe_by_tick = {
            state.get("tick", i): (state, action)
            for i, (state, action) in enumerate(probe_pairs)
        }

        sim_pairs = []
        for tick in sorted(set(target_by_tick) & set(probe_by_tick)):
            target_state, target_action = target_by_tick[tick]
            _, probe_action = probe_by_tick[tick]
            distance = actions_distance(probe_action, target_action)
            pair = {
                "turn": tick,
                "probe_action": probe_action,
                "target_action": target_action,
                "distance": round(distance, 4),
                "target_state": target_state,
            }
            sim_pairs.append(pair)
            all_pairs.append(pair)

        per_simulation.append(
            {
                "file": filename,
                "num_turns": len(sim_pairs),
            }
        )

    return {
        "probe_id": probe_id,
        "description": "probe (p0) vs target (p1) — action comparison per tick",
        "total_turns": len(all_pairs),
        "num_simulations": len(per_simulation),
        "per_simulation": per_simulation,
        "pairs": all_pairs,
    }


